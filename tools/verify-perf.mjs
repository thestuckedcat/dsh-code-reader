// Independent performance-measurement runner for the S4-prep slice
// (docs/ai-summary-perf-contract.md §2). It never modifies production code:
// it generates SYNTHETIC Atlas fixtures, imports them through the real isolated
// engine, times real engine CLI/in-process projections, starts the real pinned
// dsh web and runs the Chromium perf probe.
//
// Usage: node tools/verify-perf.mjs [--with-repo-tests]
