#!/usr/bin/env node
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8').replaceAll('\r\n','\n');
const reference=read('demo/code-view/index.html');
const wrap=p=>`(function(require){var module={exports:{}};\n${read(p)}\nreturn module.exports;})(function(id){if(id==='./scenario.cjs')return scenarios;throw Error('unknown local module');})`;
const hash=createHash('sha256').update(reference).digest('hex');
const output=`// Generated by tools/build-workbench.mjs. Canonical Demo SHA256: ${hash}\nwindow.__ModuleLoader__.load({id:'@local/dsh-code-reader',factory:function(require){\n'use strict';\nconst scenarios=${wrap('client/scenario.cjs')};\nconst documents=${wrap('client/document.cjs')};\nconst models=${wrap('client/model.cjs')};\nconst entry=${wrap('client/entry.cjs')};\nconst reference=${JSON.stringify(reference)};\nreturn entry.createPlugin(require('react'),documents,models,reference);\n}});\n`;
if(process.argv.includes('--check')) {
  if(read('bundle/client.js')!==output)throw Error('bundle/client.js is stale; run node tools/build-workbench.mjs');
  console.log(`workbench bundle current; Demo sha256=${hash}`);
} else {
  writeFileSync(new URL('bundle/client.js',root),output);
  console.log(`built ${Buffer.byteLength(output)} bytes; Demo sha256=${hash}`);
}
