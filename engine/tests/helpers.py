def make_bootstrap(tmp_path: Path, *, tree: Optional[Dict[str, Path]] = None) -> SimpleNamespace:
    """Create repos + bootstrap in a temp dir without invoking the CLI."""
    from code_learning.state import State, init_bootstrap

    tmp_path = Path(tmp_path)
    tree = tree or sample_repo_tree(tmp_path / "synthetic")
    state_dir = tmp_path / "state"
    inbox_dir = tmp_path / "inbox"
    output_root = tmp_path / "output"
    bootstrap_path = tmp_path / "bootstrap.json"
    data = init_bootstrap(
        out_path=bootstrap_path,
        state_dir=state_dir,
        inbox_dir=inbox_dir,
        output_root=output_root,
        roots={"synthetic-root": tree["root"]},
        profile_ref="unittest",
        scope_ref="local",
        scope_generation=1,
    )
    state = State(data, bootstrap_path)
    return SimpleNamespace(
        tmp_path=tmp_path,
        tree=tree,
        state=state,
        bootstrap=data,
        bootstrap_path=bootstrap_path,
        state_dir=state_dir,
        inbox_dir=inbox_dir,
        output_root=output_root,
        root=tree["root"],
        umd=tree["umd"],
        uapi=tree["uapi"],
        kmd=tree["kmd"],
    )


