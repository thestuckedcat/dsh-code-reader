def run_cli(
    bootstrap_path: Path,
    *args: str,
    expect: Optional[int] = 0,
    stdin: Optional[str] = None,
) -> subprocess.CompletedProcess:
    """Run ``python -m code_learning.cli`` from the engine root."""
    command = [sys.executable, "-m", "code_learning.cli", "--bootstrap", str(bootstrap_path), *args]
    completed = subprocess.run(
        command,
        cwd=str(ENGINE_DIR),
        input=stdin,
        capture_output=True,
        text=True,
        encoding="utf-8",
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        timeout=120,
    )
    if expect is not None:
        if completed.returncode != expect:
            raise AssertionError(
                f"CLI exited {completed.returncode}, expected {expect}\n"
                f"args={args}\nstdout={completed.stdout}\nstderr={completed.stderr}"
            )
    return completed


def cli_json(bootstrap_path: Path, *args: str, expect: Optional[int] = 0) -> Dict[str, Any]:
    completed = run_cli(bootstrap_path, *args, expect=expect)
    try:
        value = json.loads(completed.stdout)
    except json.JSONDecodeError as error:  # pragma: no cover - test diagnostic
        raise AssertionError(f"CLI stdout is not JSON: {completed.stdout!r} ({error})")
    return value


