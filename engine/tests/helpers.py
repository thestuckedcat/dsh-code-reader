KMD_DRIVER = """#include <linux/workqueue.h>
#include "job_queue.h"

static void job_complete(struct work_struct *work)
{
    struct job_work *job = container_of(work, struct job_work, work);
    job->state = JOB_STATE_DONE;
}

static int job_enqueue(struct job_work *job)
{
    queue_work(job_queue_wq, &job->work);
    return 0;
}

long job_dispatch(unsigned int cmd, unsigned long arg)
{
    struct job_work *job;
    switch (cmd) {
    case JOB_IOCTL_SUBMIT:
        job = kzalloc(sizeof(*job), GFP_KERNEL);
        if (!job)
            return -ENOMEM;
        return job_enqueue(job);
    default:
        return -ENOTTY;
    }
}
"""

