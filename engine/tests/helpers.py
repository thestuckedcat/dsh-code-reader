def envelope(kind: str, payload: Dict[str, Any], *, record_id: Optional[str] = None) -> Dict[str, Any]:
    import hashlib as _hashlib

    record = record_id or _hashlib.sha256(
        (kind + json.dumps(payload, sort_keys=True)).encode("utf-8")
    ).hexdigest()[:32]
    return {
        "schema_version": "0.1",
        "record_kind": kind,
        "record_id": record,
        "payload": payload,
        "provenance": {
            "producer_kind": "synthetic-fixture",
            "producer_version": "0.8.0",
            "task_id": "unittest",
            "input_hash": "",
            "configuration_id": None,
            "evidence_ids": [],
        },
    }


def write_snapshot_dir(
    directory: Path,
    graph_payload: Dict[str, Any],
    manifest_overrides: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Write a valid Atlas 0.1 snapshot pair and return its hashes/metadata."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    graph_document = envelope("graph", graph_payload)
    graph_bytes = (json.dumps(graph_document, indent=2, sort_keys=True) + "\n").encode("utf-8")
    graph_path = write_bytes(directory / "graph.json", graph_bytes)
    graph_hash = sha256_file(graph_path)
    manifest_payload: Dict[str, Any] = {
        "snapshot_id": directory.name,
        "analysis_id": f"analysis-{directory.name}",
        "input_files": {},
        "workspace_roots": ["synthetic-root"],
        "workspace_revisions": {"synthetic-root": "fixture-rev"},
        "scope": {"selected_scope": "fixture"},
        "coverage": {
            "selected_scope": "fixture",
            "total_available_units": 0,
            "processed_units": 0,
            "parsed": 0,
            "reused": 0,
            "failed": [],
            "pending_units": [],
            "complete_call_chain": False,
            "whole_program_complete": False,
            "requested_scope_complete": True,
            "capabilities": {
                "direct_calls": "ready",
                "types": "ready",
                "global_objects": "ready",
                "locks": "not_requested",
                "data_flow": "not_requested",
                "cfg": "unsupported",
            },
        },
        "schema_version": "0.1",
        "tool_version": "0.8.0",
        "graph_hash": graph_hash,
    }
    if manifest_overrides:
        manifest_payload.update(manifest_overrides)
    manifest_document = envelope("analysis_manifest", manifest_payload)
    manifest_path = write_json(directory / "analysis_manifest.json", manifest_document)
    return {
        "directory": directory,
        "graph_path": graph_path,
        "manifest_path": manifest_path,
        "graph_hash": graph_hash,
        "manifest_hash": sha256_file(manifest_path),
        "manifest_payload": manifest_payload,
        "graph_document": graph_document,
        "manifest_document": manifest_document,
    }


